import { AnalysisResult, CLASSIFICATION_LABELS } from '../analysis/types';

export function generateTextReport(result: AnalysisResult): string {
  const dateStr = new Date(result.timestamp).toLocaleString();
  const findingsText = result.findings.length > 0
    ? result.findings.map((f, i) => `
--------------------------------------------------------
[Finding ${i + 1}] ${(f.categoryName || f.category || 'Dark Pattern').toUpperCase()} — ${f.title || 'Untitled Finding'}
Classification: ${CLASSIFICATION_LABELS[f.classification] || f.classification || 'Potential Dark Pattern'}
Severity: ${(f.severity || 'medium').toUpperCase()} | Evidence Strength: ${(f.evidenceStrength || 'limited').toUpperCase()}
Observed Evidence: "${f.evidence || ''}"
${f.elementSelector ? `DOM Element Selector: ${f.elementSelector}\n` : ''}Why Flagged: ${f.whyFlagged}
Recommended Action: ${f.recommendedAction}
${f.limitations && f.limitations.length > 0 ? `Known Limitations: ${f.limitations.join('; ')}\n` : ''}${f.missingEvidence && f.missingEvidence.length > 0 ? `Unverified / Missing: ${f.missingEvidence.join('; ')}\n` : ''}`).join('\n')
    : 'No significant manipulative patterns detected.';

  const recommendationsText = result.recommendations.length > 0
    ? result.recommendations.map(r => `• ${r}`).join('\n')
    : 'None.';

  const limitationsText = result.limitations.length > 0
    ? result.limitations.map(l => `• ${l}`).join('\n')
    : 'None noted.';

  return `========================================================
CLEARCHOICE AI — DARK PATTERN & EVIDENCE AUDIT REPORT
========================================================

Domain: ${result.pageDomain}
URL: ${result.pageUrl}
Page Title: ${result.pageTitle}
Scan Timestamp: ${dateStr}
Risk Score: ${result.riskScore}/100 [${result.riskLevel}]
Analysis Engine: ${result.analysisMode.toUpperCase()}
AI Contextual Support: ${result.aiAvailable ? 'YES (Google Gemini)' : 'NO (Deterministic Rules Only)'}

VERIFICATION SUMMARY:
• Total Candidates Evaluated: ${result.findings.length}
• Verified Deceptive: ${result.verifiedCount}
• Strong Evidence: ${result.strongCount}
• Potential Dark Patterns: ${result.potentialCount}
• Insufficient Evidence: ${result.insufficientCount}

EXECUTIVE SUMMARY:
${result.summary}

EVALUATED FINDINGS:
${findingsText}

RECOMMENDED CONSUMER ACTIONS:
${recommendationsText}

LIMITATIONS & UNCERTAINTIES:
${limitationsText}

========================================================
DISCLAIMER:
This report is an automated assessment based solely on observable
client-side webpage elements. It is intended to assist consumer awareness
and does NOT constitute formal legal advice, judicial finding of fraud,
or certified merchant audit.
========================================================
Generated by ClearChoice AI — Evidence-Driven Consumer Protection
`;
}

export function generateJsonReport(result: AnalysisResult): string {
  return JSON.stringify(result, null, 2);
}

export async function copyReportToClipboard(result: AnalysisResult): Promise<boolean> {
  try {
    const text = generateTextReport(result);
    await navigator.clipboard.writeText(text);
    return true;
  } catch (err) {
    console.error('Failed to copy report to clipboard:', err);
    return false;
  }
}

export function downloadJsonReport(result: AnalysisResult): void {
  const jsonStr = generateJsonReport(result);
  const blob = new Blob([jsonStr], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  const safeDomain = result.pageDomain.replace(/[^a-z0-9]/gi, '_');
  a.download = `clearchoice-report-${safeDomain}-${result.timestamp}.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function downloadTextReport(result: AnalysisResult): void {
  const textStr = generateTextReport(result);
  const blob = new Blob([textStr], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  const safeDomain = result.pageDomain.replace(/[^a-z0-9]/gi, '_');
  a.download = `clearchoice-audit-${safeDomain}-${result.timestamp}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
